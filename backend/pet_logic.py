"""Логика кормления питомца.

Вынесла сюда отдельно, чтобы можно было тестировать без базы и без FastAPI.
"""

MAX_FULLNESS = 100
FEED_STEP = 10


def next_fullness(current: int, step: int = FEED_STEP) -> int:
    """Считает сытость после кормления.

    Обычно +10, но больше 100 не бывает. Если пришло отрицательное число,
    значит с данными что-то не так, поэтому кидаем ошибку.
    """
    if current < 0:
        raise ValueError("Сытость не может быть отрицательной")
    return min(MAX_FULLNESS, current + step)
